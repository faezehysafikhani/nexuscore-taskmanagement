    private static readonly Dictionary<(int Year, int Month, int Day), string> LunarByDate =
        Lunar.GroupBy(h => (h.Year, h.Month, h.Day)).ToDictionary(g => g.Key, g => g.First().Reason);

    public string? GetReason(DateOnly date)
    {
        var asDateTime = date.ToDateTime(TimeOnly.MinValue);
        int year, month, day;
        try
        {
            year = Jalali.GetYear(asDateTime);
            month = Jalali.GetMonth(asDateTime);
            day = Jalali.GetDayOfMonth(asDateTime);
        }
        catch (ArgumentOutOfRangeException)
        {
            return null; // outside the years the Persian calendar can express
        }

        foreach (var (solarMonth, solarDay, reason) in Solar)
        {
            if (solarMonth == month && solarDay == day)
            {
                return reason;
            }
        }

        return LunarByDate.GetValueOrDefault((year, month, day));
    }
